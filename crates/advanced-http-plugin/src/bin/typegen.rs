//! Generate the Property Inspector's TypeScript contracts and action metadata.

use std::path::Path;

use advanced_http_client::HttpMethod;
use serde_json::json;

fn main() -> anyhow::Result<()> {
    advanced_http_plugin::force_link();

    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let generated = root.join("pi/src/generated");
    std::fs::create_dir_all(&generated)?;

    write_contracts(&generated.join("contracts.ts"))?;
    write_actions(&generated.join("actions.ts"))?;
    Ok(())
}

fn write_contracts(path: &Path) -> anyhow::Result<()> {
    streamdeck_plugin::export_typescript(path)?;
    let text = std::fs::read_to_string(path)?.replace("\ntype ", "\nexport type ");
    // The generator pads fields with `, `; keep the committed output clean.
    let text = format!(
        "{}\n",
        text.lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
            .trim_end()
    );
    std::fs::write(path, text)?;
    Ok(())
}

fn write_actions(path: &Path) -> anyhow::Result<()> {
    let actions: Vec<_> = advanced_http_plugin::actions::all_actions()
        .into_iter()
        .map(|action| {
            json!({
                "uuid": action.uuid,
                "method": action.method.map(HttpMethod::as_str),
                "controller": action.controller.as_str(),
                "legacy": action.legacy,
            })
        })
        .collect();
    let methods: Vec<&str> = HttpMethod::ALL
        .iter()
        .map(|method| method.as_str())
        .collect();
    let no_body: Vec<&str> = HttpMethod::ALL
        .iter()
        .filter(|method| !method.has_body())
        .map(|method| method.as_str())
        .collect();

    let text = format!(
        "// Generated by advanced-http-plugin typegen. Do not edit.\n\
         \n\
         export type ControllerKind = \"keypad\" | \"encoder\";\n\
         export type ActionMeta = {{ uuid: string; method: string | null; controller: ControllerKind; legacy: boolean }};\n\
         \n\
         export const ACTIONS: readonly ActionMeta[] = {};\n\
         \n\
         export const METHODS: readonly string[] = {};\n\
         \n\
         export const NO_BODY_METHODS: readonly string[] = {};\n",
        serde_json::to_string_pretty(&actions)?,
        serde_json::to_string_pretty(&methods)?,
        serde_json::to_string_pretty(&no_body)?,
    );
    std::fs::write(path, text)?;
    Ok(())
}
